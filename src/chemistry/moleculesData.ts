export type ElementSymbol = 'H' | 'B' | 'C' | 'N' | 'O' | 'F' | 'P' | 'S' | 'Cl' | 'Xe';

export interface AtomNode {
  id: string;
  element: ElementSymbol;
  /** 2D Sketcher Canvas coordinates (centered around 0,0 in Angstrom-like units) */
  x2d: number;
  y2d: number;
  /** 3D Cartesian coordinates in Angstroms */
  x3d: number;
  y3d: number;
  z3d: number;
  formalCharge?: number;
}

export interface BondEdge {
  id: string;
  source: string;
  target: string;
  order: 1 | 2 | 3;
  stereo?: 'none' | 'wedge' | 'dash';
}

export type OrbitalBasisType =
  | 's'
  | 'px'
  | 'py'
  | 'pz'
  | 'dz2'
  | 'dx2y2'
  | 'dxy'
  | 'dxz'
  | 'dyz';

export interface LCAOContribution {
  atomId: string;
  element: ElementSymbol;
  orbital: OrbitalBasisType;
  label: string; // e.g., "O 2pz"
  coeff: number; // Weight in [-1, 1]
}

export interface FragmentOrbital {
  id: string;
  side: 'left' | 'right';
  label: string; // e.g. "O 2pz" or "SALC (a1)"
  fragmentName: string; // e.g. "Central O Atom" or "2 H (1s) LGOs"
  energy: number; // in eV
  irrep: string;  // Mulliken symbol e.g. "a1"
  degeneracy: number;
  electrons: number;
}

export interface MolecularOrbital {
  id: string;
  label: string; // e.g. "1b1", "3a1", "1e1g (π)"
  irrepSymbol: string; // Match IrreducibleRepresentation.symbol e.g. "B1", "A1", "E1g"
  irrepId: string; // Match IrreducibleRepresentation.id e.g. "B1", "A1", "E1g"
  energy: number; // in eV
  occupancy: 0 | 1 | 2; // Number of electrons in this spatial orbital
  bondingType: 'bonding' | 'non-bonding' | 'antibonding';
  interactionType: 'σ' | 'π' | 'n (Lone Pair)' | 'σ*' | 'π*' | 'δ';
  nodalPlanes: number;
  isHOMO?: boolean;
  isLUMO?: boolean;
  degenerateGroup?: string; // If part of a degenerate E or T level, share same group ID
  correlatedFragmentIds: string[]; // Links to FragmentOrbital.id for correlation lines
  lcao: LCAOContribution[];
  description: string;
}

export interface MoleculeEntry {
  id: string;
  name: string;
  iupacName: string;
  formula: string;
  smiles: string;
  pubchemCid: number;
  pointGroupId: string; // Key in POINT_GROUPS
  schoenflies: string;
  valenceElectrons: number;
  bondOrder: number;
  dipoleMomentDebye: number;
  leftFragmentTitle: string;
  rightFragmentTitle: string;
  atoms: AtomNode[];
  bonds: BondEdge[];
  fragmentOrbitals: FragmentOrbital[];
  molecularOrbitals: MolecularOrbital[];
  reducibleRepresentations: {
    label: string;
    characters: number[];
    decomposition: string;
  }[];
}

